const stored = (() => { try { return localStorage.getItem('ff:lang'); } catch { return null; } })();
let lang = stored || ((navigator.language || 'en').toLowerCase().match(/^(nb|nn|no)/) ? 'nb' : 'en');

export function t(key, vars = {}) {
  let s = (dict[lang] && dict[lang][key]) ?? dict.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
export function getLang() { return lang; }
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('ff:lang', l); } catch {}
  document.documentElement.lang = l === 'nb' ? 'nb' : 'en';
  applyStatic();
}
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPh)); });
}
document.documentElement.lang = lang === 'nb' ? 'nb' : 'en';
